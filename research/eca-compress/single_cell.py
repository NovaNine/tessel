"""Same measure, but from a single black cell on a wide ring: no randomness goes in, so any
incompressibility has to be generated by the rule itself. Ring is wide enough that the light cone
(2*T+1) never wraps around."""
import json, zlib
from classes import reps
from measure import pack

T = 1024
W = 2 * T + 3

def run(rule):
    row = [0] * W; row[W // 2] = 1
    table = [(rule >> n) & 1 for n in range(8)]
    rows = []
    for _ in range(T):
        rows.append(row)
        row = [table[(row[i - 1] << 2) | (row[i] << 1) | row[(i + 1) % W]] for i in range(W)]
    return rows

def light_cone(rows):
    # only the cells the single seed can have influenced, so blank margins don't flatter anyone
    c = W // 2
    return [r[c - t: c + t + 1] for t, r in enumerate(rows)]

out = {}
for r in reps:
    rows = run(r)
    # Rules whose 000 -> 1 flip the whole background; skip the cone trick for them and use full rows.
    data = rows if (r & 1) else light_cone(rows)
    flat = [[b for b in row] for row in data]
    raw = pack(flat)
    out[r] = round(len(zlib.compress(raw, 9)) / len(raw), 4)
json.dump({"params": {"steps": T, "width": W}, "rules": out}, open("single_cell.json", "w"), indent=1)
s = sorted(out.items(), key=lambda kv: -kv[1])
rank = {r: i + 1 for i, (r, _) in enumerate(s)}
for r, v in s[:12]: print(r, v)
print("---")
for r in (30, 45, 106, 110, 54, 90, 150, 105, 60, 18, 22, 126):
    print(f"rule {r:3d}: rank {rank[r]:2d}/88 ratio {out[r]}")
